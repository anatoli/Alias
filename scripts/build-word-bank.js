function uniqPad(base, extras, target) {
  const seen = new Set()
  const out = []
  for (const w of base.concat(extras)) {
    const key = String(w).trim()
    if (!key || seen.has(key.toLowerCase())) continue
    seen.add(key.toLowerCase())
    out.push(key)
    if (out.length >= target) break
  }
  // deterministic filler if still short
  let i = 1
  while (out.length < target) {
    const filler = `Слово ${out.length + 1}`
    if (!seen.has(filler.toLowerCase())) {
      seen.add(filler.toLowerCase())
      out.push(filler)
    }
    i++
    if (i > 5000) break
  }
  return out.slice(0, target)
}

