function extract(startLabel, endLabel) {
  const a = w.indexOf(startLabel)
  const b = w.indexOf(endLabel, a + 1)
  const chunk = w.slice(a, b < 0 ? undefined : b)
  return (chunk.match(/"([^"\\]|\\.)*"/g) || []).map((s) => JSON.parse(s))
}

